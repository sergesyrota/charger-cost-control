# PlatformIO pre-build hook: lightly minifies web/index.html and gzips it into src/web/ui_gz.h
# (byte array + length). If web/index.html is missing, emits a tiny placeholder page. Rewrites the
# header only when the content changed (avoids needless rebuilds). Owner: ui.
# Can also be run standalone: python3 tools/build_ui.py
#
# Minification is deliberately conservative (line-based, newlines kept so JS ASI is unaffected):
#   - strip leading/trailing whitespace of every line
#   - drop empty lines
#   - drop lines that are entirely a /* ... */ comment (CSS section markers, JS banners)
# Nothing inside a line is touched, so strings/regexes/template literals stay intact.
import gzip
import os
import re

try:
    Import("env")  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "web", "index.html")
OUT = os.path.join(ROOT, "src", "web", "ui_gz.h")
PLACEHOLDER = b"<!doctype html><meta charset=utf-8><title>Charger</title><p>UI not built. <a href=/api/status>/api/status</a>"
WHOLE_LINE_COMMENT = re.compile(r"^/\*[^*]*(\*(?!/)[^*]*)*\*/$")


def minify(text):
    out = []
    for line in text.split("\n"):
        s = line.strip()
        if not s or WHOLE_LINE_COMMENT.match(s):
            continue
        out.append(s)
    return "\n".join(out) + "\n"


def build():
    if os.path.exists(SRC):
        src = open(SRC, "rb").read()
        raw = minify(src.decode("utf-8")).encode("utf-8")
    else:
        src = raw = PLACEHOLDER
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
    text = (
        "// GENERATED by tools/build_ui.py from web/index.html — do not edit, not committed.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        "static const uint8_t ui_gz[] = {\n" + "\n".join(lines) + "\n};\n"
        "static const size_t ui_gz_len = %d;  // minified %d bytes (source %d)\n" % (len(gz), len(raw), len(src))
    )
    if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != text:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w", encoding="utf-8") as f:
            f.write(text)
    print("UI: %d bytes source, %d minified -> %d gzipped%s"
          % (len(src), len(raw), len(gz), "" if os.path.exists(SRC) else " (placeholder)"))


build()
