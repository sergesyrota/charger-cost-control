# PlatformIO pre-build hook: gzips web/index.html into src/web/ui_gz.h (byte array + length).
# If web/index.html is missing, emits a tiny placeholder page. Rewrites the header only when the
# content changed (avoids needless rebuilds). Owner: ui. Can also be run standalone: python3 tools/build_ui.py
import gzip
import os

try:
    Import("env")  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "web", "index.html")
OUT = os.path.join(ROOT, "src", "web", "ui_gz.h")
PLACEHOLDER = b"<!doctype html><meta charset=utf-8><title>Charger</title><p>UI not built. <a href=/api/status>/api/status</a>"


def build():
    raw = open(SRC, "rb").read() if os.path.exists(SRC) else PLACEHOLDER
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 20):
        lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
    text = (
        "// GENERATED by tools/build_ui.py from web/index.html — do not edit, not committed.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        "static const uint8_t ui_gz[] = {\n" + "\n".join(lines) + "\n};\n"
        "static const size_t ui_gz_len = %d;  // raw %d bytes\n" % (len(gz), len(raw))
    )
    if not os.path.exists(OUT) or open(OUT).read() != text:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
    print("UI: %d bytes -> %d gzipped%s" % (len(raw), len(gz), "" if os.path.exists(SRC) else " (placeholder)"))


build()
